export function hashAccessToken(rawToken: string): string {
  return crypto.createHash('sha256').update(rawToken.trim(), 'utf8').digest('hex');
}

export function isValidAccessToken(rawToken: string): boolean {
  const trimmed = rawToken.trim();
  if (trimmed.length !== 10) return false;
  return PREISSUED_TOKEN_HASHES.has(hashAccessToken(trimmed));
}
